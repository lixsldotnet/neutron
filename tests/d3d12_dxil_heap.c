#define THREADS 32

static int fail(const char *what, HRESULT hr)
{
    printf("FAIL %s: hr=0x%08lx\n", what, (unsigned long)hr);
    return 1;
}

static ID3D12Resource *make_buffer(ID3D12Device *dev, D3D12_HEAP_TYPE type, UINT64 size, D3D12_RESOURCE_FLAGS flags,
                                   D3D12_RESOURCE_STATES state)
{
    D3D12_HEAP_PROPERTIES hp = { type };
    D3D12_RESOURCE_DESC rd = { 0 };
    ID3D12Resource *res = NULL;
    rd.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER;
    rd.Width = size;
    rd.Height = 1;
    rd.DepthOrArraySize = 1;
    rd.MipLevels = 1;
    rd.SampleDesc.Count = 1;
    rd.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    rd.Flags = flags;
    ID3D12Device_CreateCommittedResource(dev, &hp, D3D12_HEAP_FLAG_NONE, &rd, state, NULL, &IID_ID3D12Resource,
                                         (void **)&res);
    return res;
}

static UINT f2u(float f) { UINT u; memcpy(&u, &f, 4); return u; }

int main(void)
{
    ID3D12Device *dev = NULL;
    ID3D12CommandQueue *queue = NULL;
    ID3D12CommandAllocator *alloc = NULL;
    ID3D12GraphicsCommandList *list = NULL;
    ID3D12RootSignature *rs = NULL;
    ID3D12PipelineState *pso = NULL;
    ID3D12DescriptorHeap *heap = NULL, *sheap = NULL;
    ID3D12Fence *fence = NULL;
    HRESULT hr;

    if (FAILED(hr = D3D12CreateDevice(NULL, D3D_FEATURE_LEVEL_11_0, &IID_ID3D12Device, (void **)&dev)))
        return fail("D3D12CreateDevice", hr);
    if (FAILED(hr = ID3D12Device_CreateRootSignature(dev, 0, cs_dxil, sizeof(cs_dxil), &IID_ID3D12RootSignature,
            (void **)&rs)))
        return fail("CreateRootSignature (from the shader)", hr);
    D3D12_COMPUTE_PIPELINE_STATE_DESC pd = { 0 };
    pd.pRootSignature = rs;
    pd.CS.pShaderBytecode = cs_dxil;
    pd.CS.BytecodeLength = sizeof(cs_dxil);
    if (FAILED(hr = ID3D12Device_CreateComputePipelineState(dev, &pd, &IID_ID3D12PipelineState, (void **)&pso)))
        return fail("CreateComputePipelineState", hr);

    D3D12_COMMAND_QUEUE_DESC qd = { D3D12_COMMAND_LIST_TYPE_DIRECT };
    ID3D12Device_CreateCommandQueue(dev, &qd, &IID_ID3D12CommandQueue, (void **)&queue);
    ID3D12Device_CreateCommandAllocator(dev, D3D12_COMMAND_LIST_TYPE_DIRECT, &IID_ID3D12CommandAllocator,
                                        (void **)&alloc);
    ID3D12Device_CreateCommandList(dev, 0, D3D12_COMMAND_LIST_TYPE_DIRECT, alloc, pso, &IID_ID3D12GraphicsCommandList,
                                   (void **)&list);

    D3D12_HEAP_PROPERTIES hp = { D3D12_HEAP_TYPE_DEFAULT };
    D3D12_RESOURCE_DESC td = { 0 };
    td.Dimension = D3D12_RESOURCE_DIMENSION_TEXTURE2D;
    td.Width = 4;
    td.Height = 4;
    td.DepthOrArraySize = 1;
    td.MipLevels = 1;
    td.Format = DXGI_FORMAT_R32G32B32A32_FLOAT;
    td.SampleDesc.Count = 1;
    ID3D12Resource *tex = NULL;
    ID3D12Device_CreateCommittedResource(dev, &hp, D3D12_HEAP_FLAG_NONE, &td, D3D12_RESOURCE_STATE_COPY_DEST, NULL,
                                         &IID_ID3D12Resource, (void **)&tex);
    ID3D12Resource *upload = make_buffer(dev, D3D12_HEAP_TYPE_UPLOAD, 1024 + THREADS * 4, D3D12_RESOURCE_FLAG_NONE,
                                         D3D12_RESOURCE_STATE_GENERIC_READ);
    unsigned char *up = NULL;
    ID3D12Resource_Map(upload, 0, NULL, (void **)&up);
    for (int y = 0; y < 4; y++)
        for (int x = 0; x < 4; x++) {
            float *p = (float *)(up + y * 256 + x * 16);
            p[0] = x + 10 * y;
            p[1] = p[2] = p[3] = 0;
        }
    for (int i = 0; i < THREADS; i++)
        ((UINT *)(up + 1024))[i] = 1000 + i;
    ID3D12Resource_Unmap(upload, 0, NULL);
    D3D12_TEXTURE_COPY_LOCATION dst = { tex, D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX };
    D3D12_TEXTURE_COPY_LOCATION src = { upload, D3D12_TEXTURE_COPY_TYPE_PLACED_FOOTPRINT };
    src.PlacedFootprint.Footprint.Format = DXGI_FORMAT_R32G32B32A32_FLOAT;
    src.PlacedFootprint.Footprint.Width = 4;
    src.PlacedFootprint.Footprint.Height = 4;
    src.PlacedFootprint.Footprint.Depth = 1;
    src.PlacedFootprint.Footprint.RowPitch = 256;
    ID3D12GraphicsCommandList_CopyTextureRegion(list, &dst, 0, 0, 0, &src, NULL);
    ID3D12Resource *sb = make_buffer(dev, D3D12_HEAP_TYPE_DEFAULT, THREADS * 4, D3D12_RESOURCE_FLAG_NONE,
                                     D3D12_RESOURCE_STATE_COPY_DEST);
    ID3D12GraphicsCommandList_CopyBufferRegion(list, sb, 0, upload, 1024, THREADS * 4);
    D3D12_RESOURCE_BARRIER b[2] = { 0 };
    b[0].Type = b[1].Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
    b[0].Transition.pResource = tex;
    b[1].Transition.pResource = sb;
    for (int i = 0; i < 2; i++) {
        b[i].Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
        b[i].Transition.StateBefore = D3D12_RESOURCE_STATE_COPY_DEST;
        b[i].Transition.StateAfter = D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE;
    }
    ID3D12GraphicsCommandList_ResourceBarrier(list, 2, b);

    ID3D12Resource *out = make_buffer(dev, D3D12_HEAP_TYPE_DEFAULT, THREADS * 8,
                                      D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS, D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
    ID3D12Resource *rb = make_buffer(dev, D3D12_HEAP_TYPE_READBACK, THREADS * 8, D3D12_RESOURCE_FLAG_NONE,
                                     D3D12_RESOURCE_STATE_COPY_DEST);

    /* heap: [0] unused, [1] UAV raw out, [2] SRV texture, [3] SRV structured */
    D3D12_DESCRIPTOR_HEAP_DESC hd = { D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV, 4,
                                      D3D12_DESCRIPTOR_HEAP_FLAG_SHADER_VISIBLE };
    ID3D12Device_CreateDescriptorHeap(dev, &hd, &IID_ID3D12DescriptorHeap, (void **)&heap);
    UINT inc = ID3D12Device_GetDescriptorHandleIncrementSize(dev, D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV);
    D3D12_CPU_DESCRIPTOR_HANDLE h0 = ID3D12DescriptorHeap_GetCPUDescriptorHandleForHeapStart(heap), h;
    D3D12_UNORDERED_ACCESS_VIEW_DESC ud = { DXGI_FORMAT_R32_TYPELESS, D3D12_UAV_DIMENSION_BUFFER };
    ud.Buffer.NumElements = THREADS * 2;
    ud.Buffer.Flags = D3D12_BUFFER_UAV_FLAG_RAW;
    h.ptr = h0.ptr + inc * 1;
    ID3D12Device_CreateUnorderedAccessView(dev, out, NULL, &ud, h);
    D3D12_SHADER_RESOURCE_VIEW_DESC sd = { DXGI_FORMAT_R32G32B32A32_FLOAT, D3D12_SRV_DIMENSION_TEXTURE2D,
                                           D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING };
    sd.Texture2D.MipLevels = 1;
    h.ptr = h0.ptr + inc * 2;
    ID3D12Device_CreateShaderResourceView(dev, tex, &sd, h);
    D3D12_SHADER_RESOURCE_VIEW_DESC bd = { DXGI_FORMAT_UNKNOWN, D3D12_SRV_DIMENSION_BUFFER,
                                           D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING };
    bd.Buffer.NumElements = THREADS;
    bd.Buffer.StructureByteStride = 4;
    h.ptr = h0.ptr + inc * 3;
    ID3D12Device_CreateShaderResourceView(dev, sb, &bd, h);

    D3D12_DESCRIPTOR_HEAP_DESC shd = { D3D12_DESCRIPTOR_HEAP_TYPE_SAMPLER, 2, D3D12_DESCRIPTOR_HEAP_FLAG_SHADER_VISIBLE };
    ID3D12Device_CreateDescriptorHeap(dev, &shd, &IID_ID3D12DescriptorHeap, (void **)&sheap);
    UINT sinc = ID3D12Device_GetDescriptorHandleIncrementSize(dev, D3D12_DESCRIPTOR_HEAP_TYPE_SAMPLER);
    D3D12_SAMPLER_DESC smp = { D3D12_FILTER_MIN_MAG_MIP_POINT, D3D12_TEXTURE_ADDRESS_MODE_CLAMP,
                               D3D12_TEXTURE_ADDRESS_MODE_CLAMP, D3D12_TEXTURE_ADDRESS_MODE_CLAMP };
    smp.MaxLOD = D3D12_FLOAT32_MAX;
    h.ptr = ID3D12DescriptorHeap_GetCPUDescriptorHandleForHeapStart(sheap).ptr + sinc;
    ID3D12Device_CreateSampler(dev, &smp, h);

    ID3D12DescriptorHeap *heaps[2] = { heap, sheap };
    UINT consts[4] = { 1, 2, 3, 1 };
    ID3D12GraphicsCommandList_SetDescriptorHeaps(list, 2, heaps);
    ID3D12GraphicsCommandList_SetComputeRootSignature(list, rs);
    ID3D12GraphicsCommandList_SetComputeRoot32BitConstants(list, 0, 4, consts, 0);
    ID3D12GraphicsCommandList_Dispatch(list, 1, 1, 1);
    b[0].Transition.pResource = out;
    b[0].Transition.StateBefore = D3D12_RESOURCE_STATE_UNORDERED_ACCESS;
    b[0].Transition.StateAfter = D3D12_RESOURCE_STATE_COPY_SOURCE;
    ID3D12GraphicsCommandList_ResourceBarrier(list, 1, b);
    ID3D12GraphicsCommandList_CopyResource(list, rb, out);
    if (FAILED(hr = ID3D12GraphicsCommandList_Close(list)))
        return fail("Close", hr);
    ID3D12CommandQueue_ExecuteCommandLists(queue, 1, (ID3D12CommandList **)&list);
    ID3D12Device_CreateFence(dev, 0, D3D12_FENCE_FLAG_NONE, &IID_ID3D12Fence, (void **)&fence);
    HANDLE ev = CreateEventA(NULL, FALSE, FALSE, NULL);
    ID3D12CommandQueue_Signal(queue, fence, 1);
    ID3D12Fence_SetEventOnCompletion(fence, 1, ev);
    if (WaitForSingleObject(ev, 10000) != WAIT_OBJECT_0)
        return fail("GPU timeout", E_FAIL);

    UINT *r = NULL;
    ID3D12Resource_Map(rb, 0, NULL, (void **)&r);
    int bad = 0;
    for (UINT i = 0; i < THREADS; i++) {
        UINT w0 = f2u((float)(i % 4)), w1 = 1000 + i;
        if (r[2 * i] != w0 || r[2 * i + 1] != w1) {
            if (bad < 8)
                printf("thread %u: got 0x%08x %u, want 0x%08x %u\n", i, r[2 * i], r[2 * i + 1], w0, w1);
            bad++;
        }
    }
    if (bad) {
        printf("FAIL %d mismatches\n", bad);
        return 1;
    }
    printf("PASS all %d threads\n", THREADS);
    return 0;
}
