#define N 128

static int fail(const char *what, HRESULT hr)
{
    printf("FAIL %s: hr=0x%08lx\n", what, (unsigned long)hr);
    return 1;
}

static ID3D12Resource *make_buffer(ID3D12Device *dev, D3D12_HEAP_TYPE type, D3D12_RESOURCE_FLAGS flags,
                                   D3D12_RESOURCE_STATES state)
{
    D3D12_HEAP_PROPERTIES hp = { type };
    D3D12_RESOURCE_DESC rd = { 0 };
    ID3D12Resource *res = NULL;
    rd.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER;
    rd.Width = N * 4;
    rd.Height = 1;
    rd.DepthOrArraySize = 1;
    rd.MipLevels = 1;
    rd.SampleDesc.Count = 1;
    rd.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    rd.Flags = flags;
    ID3D12Device_CreateCommittedResource(dev, &hp, D3D12_HEAP_FLAG_NONE, &rd, state, NULL, &IID_ID3D12Resource,
                                         (void **)&res);
    return res;
}

int main(void)
{
    ID3D12Device *dev = NULL;
    ID3D12CommandQueue *queue = NULL;
    ID3D12CommandAllocator *alloc = NULL;
    ID3D12GraphicsCommandList *list = NULL;
    ID3D12RootSignature *rs = NULL;
    ID3D12PipelineState *pso = NULL;
    ID3D12Fence *fence = NULL;
    HRESULT hr;

    if (FAILED(hr = D3D12CreateDevice(NULL, D3D_FEATURE_LEVEL_11_0, &IID_ID3D12Device, (void **)&dev)))
        return fail("D3D12CreateDevice", hr);

    D3D12_ROOT_PARAMETER1 params[3] = { 0 };
    params[0].ParameterType = D3D12_ROOT_PARAMETER_TYPE_32BIT_CONSTANTS;
    params[0].Constants.ShaderRegister = 0;
    params[0].Constants.Num32BitValues = 4;
    params[1].ParameterType = D3D12_ROOT_PARAMETER_TYPE_UAV;
    params[1].Descriptor.ShaderRegister = 0;
    params[2].ParameterType = D3D12_ROOT_PARAMETER_TYPE_UAV;
    params[2].Descriptor.ShaderRegister = 1;
    D3D12_VERSIONED_ROOT_SIGNATURE_DESC rsd = { D3D_ROOT_SIGNATURE_VERSION_1_1 };
    rsd.Desc_1_1.NumParameters = 3;
    rsd.Desc_1_1.pParameters = params;
    ID3DBlob *blob = NULL, *err = NULL;
    if (FAILED(hr = D3D12SerializeVersionedRootSignature(&rsd, &blob, &err)))
        return fail("D3D12SerializeVersionedRootSignature", hr);
    if (FAILED(hr = ID3D12Device_CreateRootSignature(dev, 0, ID3D10Blob_GetBufferPointer(blob),
            ID3D10Blob_GetBufferSize(blob), &IID_ID3D12RootSignature, (void **)&rs)))
        return fail("CreateRootSignature", hr);

    D3D12_COMPUTE_PIPELINE_STATE_DESC pd = { 0 };
    pd.pRootSignature = rs;
    pd.CS.pShaderBytecode = cs_dxil;
    pd.CS.BytecodeLength = sizeof(cs_dxil);
    if (FAILED(hr = ID3D12Device_CreateComputePipelineState(dev, &pd, &IID_ID3D12PipelineState, (void **)&pso)))
        return fail("CreateComputePipelineState (DXIL)", hr);
    printf("DXIL compute PSO ok\n");

    D3D12_COMMAND_QUEUE_DESC qd = { D3D12_COMMAND_LIST_TYPE_DIRECT };
    if (FAILED(hr = ID3D12Device_CreateCommandQueue(dev, &qd, &IID_ID3D12CommandQueue, (void **)&queue)))
        return fail("CreateCommandQueue", hr);
    if (FAILED(hr = ID3D12Device_CreateCommandAllocator(dev, D3D12_COMMAND_LIST_TYPE_DIRECT,
            &IID_ID3D12CommandAllocator, (void **)&alloc)))
        return fail("CreateCommandAllocator", hr);
    if (FAILED(hr = ID3D12Device_CreateCommandList(dev, 0, D3D12_COMMAND_LIST_TYPE_DIRECT, alloc, pso,
            &IID_ID3D12GraphicsCommandList, (void **)&list)))
        return fail("CreateCommandList", hr);

    ID3D12Resource *u0 = make_buffer(dev, D3D12_HEAP_TYPE_DEFAULT, D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS,
                                     D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
    ID3D12Resource *u1 = make_buffer(dev, D3D12_HEAP_TYPE_DEFAULT, D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS,
                                     D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
    ID3D12Resource *rb0 = make_buffer(dev, D3D12_HEAP_TYPE_READBACK, D3D12_RESOURCE_FLAG_NONE,
                                      D3D12_RESOURCE_STATE_COPY_DEST);
    ID3D12Resource *rb1 = make_buffer(dev, D3D12_HEAP_TYPE_READBACK, D3D12_RESOURCE_FLAG_NONE,
                                      D3D12_RESOURCE_STATE_COPY_DEST);
    if (!u0 || !u1 || !rb0 || !rb1)
        return fail("CreateCommittedResource", E_FAIL);

    float fmul = 2.0f;
    UINT consts[4] = { 3, 5, 0, 0 };
    memcpy(&consts[2], &fmul, 4);
    ID3D12GraphicsCommandList_SetComputeRootSignature(list, rs);
    ID3D12GraphicsCommandList_SetComputeRoot32BitConstants(list, 0, 4, consts, 0);
    ID3D12GraphicsCommandList_SetComputeRootUnorderedAccessView(list, 1, ID3D12Resource_GetGPUVirtualAddress(u0));
    ID3D12GraphicsCommandList_SetComputeRootUnorderedAccessView(list, 2, ID3D12Resource_GetGPUVirtualAddress(u1));
    ID3D12GraphicsCommandList_Dispatch(list, N / 64, 1, 1);

    D3D12_RESOURCE_BARRIER b[2] = { 0 };
    for (int i = 0; i < 2; i++) {
        b[i].Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
        b[i].Transition.pResource = i ? u1 : u0;
        b[i].Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
        b[i].Transition.StateBefore = D3D12_RESOURCE_STATE_UNORDERED_ACCESS;
        b[i].Transition.StateAfter = D3D12_RESOURCE_STATE_COPY_SOURCE;
    }
    ID3D12GraphicsCommandList_ResourceBarrier(list, 2, b);
    ID3D12GraphicsCommandList_CopyResource(list, rb0, u0);
    ID3D12GraphicsCommandList_CopyResource(list, rb1, u1);
    if (FAILED(hr = ID3D12GraphicsCommandList_Close(list)))
        return fail("Close", hr);
    ID3D12CommandQueue_ExecuteCommandLists(queue, 1, (ID3D12CommandList **)&list);

    if (FAILED(hr = ID3D12Device_CreateFence(dev, 0, D3D12_FENCE_FLAG_NONE, &IID_ID3D12Fence, (void **)&fence)))
        return fail("CreateFence", hr);
    HANDLE ev = CreateEventA(NULL, FALSE, FALSE, NULL);
    ID3D12CommandQueue_Signal(queue, fence, 1);
    ID3D12Fence_SetEventOnCompletion(fence, 1, ev);
    if (WaitForSingleObject(ev, 10000) != WAIT_OBJECT_0)
        return fail("GPU timeout", E_FAIL);

    UINT *o0 = NULL, *o1 = NULL;
    D3D12_RANGE r = { 0, N * 4 };
    ID3D12Resource_Map(rb0, 0, &r, (void **)&o0);
    ID3D12Resource_Map(rb1, 0, &r, (void **)&o1);
    int bad = 0;
    UINT lanes = o1[0] % 1000;
    printf("wave size seen by the shader: %u\n", lanes);
    for (UINT x = 0; x < N; x++) {
        UINT g = x / 64, gi = x % 64;
        UINT want0 = (g * 64 + 63 - gi) * 3 + 5 + (UINT)(x * 2.0f) + g;
        UINT want1 = lanes + (x % (lanes ? lanes : 1)) * 1000;
        if (o0[x] != want0 || o1[x] != want1) {
            if (bad < 8)
                printf("mismatch at %u: outbuf %u (want %u), raw %u (want %u)\n", x, o0[x], want0, o1[x], want1);
            bad++;
        }
    }
    printf("first values: outbuf %u %u %u, raw %u %u %u\n", o0[0], o0[1], o0[64], o1[0], o1[1], o1[33]);
    if (bad) {
        printf("FAIL %d of %d values wrong\n", bad, N);
        return 1;
    }
    printf("PASS all %d values\n", N);
    return 0;
}
