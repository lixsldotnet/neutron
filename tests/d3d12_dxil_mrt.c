#define W 64
#define H 64

static int fail(const char *what, HRESULT hr)
{
    printf("FAIL %s: hr=0x%08lx\n", what, (unsigned long)hr);
    return 1;
}

static ID3D12Resource *make_buffer(ID3D12Device *dev, D3D12_HEAP_TYPE type, UINT64 size, D3D12_RESOURCE_STATES state)
{
    D3D12_HEAP_PROPERTIES hp = { type };
    D3D12_RESOURCE_DESC rd = { 0 };
    ID3D12Resource *res = NULL;
    rd.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER;
    rd.Width = size;
    rd.Height = 1;
    rd.DepthOrArraySize = 1;
    rd.MipLevels = 1;
    rd.SampleDesc.Count = 1;
    rd.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    ID3D12Device_CreateCommittedResource(dev, &hp, D3D12_HEAP_FLAG_NONE, &rd, state, NULL, &IID_ID3D12Resource,
                                         (void **)&res);
    return res;
}

static ID3D12Resource *make_texture(ID3D12Device *dev, DXGI_FORMAT format, D3D12_RESOURCE_FLAGS flags,
                                    D3D12_RESOURCE_STATES state, const D3D12_CLEAR_VALUE *clear)
{
    D3D12_HEAP_PROPERTIES hp = { D3D12_HEAP_TYPE_DEFAULT };
    D3D12_RESOURCE_DESC td = { 0 };
    ID3D12Resource *res = NULL;
    td.Dimension = D3D12_RESOURCE_DIMENSION_TEXTURE2D;
    td.Width = W;
    td.Height = H;
    td.DepthOrArraySize = 1;
    td.MipLevels = 1;
    td.Format = format;
    td.SampleDesc.Count = 1;
    td.Flags = flags;
    ID3D12Device_CreateCommittedResource(dev, &hp, D3D12_HEAP_FLAG_NONE, &td, state, clear, &IID_ID3D12Resource,
                                         (void **)&res);
    return res;
}

static void transition(ID3D12GraphicsCommandList *list, ID3D12Resource *res, D3D12_RESOURCE_STATES from,
                       D3D12_RESOURCE_STATES to)
{
    D3D12_RESOURCE_BARRIER b = { 0 };
    b.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
    b.Transition.pResource = res;
    b.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
    b.Transition.StateBefore = from;
    b.Transition.StateAfter = to;
    ID3D12GraphicsCommandList_ResourceBarrier(list, 1, &b);
}

static void copy_out(ID3D12GraphicsCommandList *list, ID3D12Resource *dst, UINT64 offset, ID3D12Resource *src,
                     DXGI_FORMAT format, UINT pitch)
{
    D3D12_TEXTURE_COPY_LOCATION d = { dst, D3D12_TEXTURE_COPY_TYPE_PLACED_FOOTPRINT };
    d.PlacedFootprint.Offset = offset;
    d.PlacedFootprint.Footprint.Format = format;
    d.PlacedFootprint.Footprint.Width = W;
    d.PlacedFootprint.Footprint.Height = H;
    d.PlacedFootprint.Footprint.Depth = 1;
    d.PlacedFootprint.Footprint.RowPitch = pitch;
    D3D12_TEXTURE_COPY_LOCATION s = { src, D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX };
    ID3D12GraphicsCommandList_CopyTextureRegion(list, &d, 0, 0, 0, &s, NULL);
}

int main(void)
{
    ID3D12Device *dev = NULL;
    ID3D12CommandQueue *queue = NULL;
    ID3D12CommandAllocator *alloc = NULL;
    ID3D12GraphicsCommandList *list = NULL;
    ID3D12RootSignature *rs = NULL;
    ID3D12PipelineState *pso = NULL;
    ID3D12DescriptorHeap *rtv_heap = NULL, *dsv_heap = NULL;
    ID3D12Fence *fence = NULL;
    HRESULT hr;

    if (FAILED(hr = D3D12CreateDevice(NULL, D3D_FEATURE_LEVEL_11_0, &IID_ID3D12Device, (void **)&dev)))
        return fail("D3D12CreateDevice", hr);
    if (FAILED(hr = ID3D12Device_CreateRootSignature(dev, 0, ps_dxil, sizeof(ps_dxil), &IID_ID3D12RootSignature,
            (void **)&rs)))
        return fail("CreateRootSignature", hr);

    D3D12_GRAPHICS_PIPELINE_STATE_DESC pd = { 0 };
    pd.pRootSignature = rs;
    pd.VS.pShaderBytecode = vs_dxil;
    pd.VS.BytecodeLength = sizeof(vs_dxil);
    pd.PS.pShaderBytecode = ps_dxil;
    pd.PS.BytecodeLength = sizeof(ps_dxil);
    for (int t = 0; t < 3; t++)
        pd.BlendState.RenderTarget[t].RenderTargetWriteMask = D3D12_COLOR_WRITE_ENABLE_ALL;
    pd.SampleMask = ~0u;
    pd.RasterizerState.FillMode = D3D12_FILL_MODE_SOLID;
    pd.RasterizerState.CullMode = D3D12_CULL_MODE_NONE;
    pd.RasterizerState.DepthClipEnable = TRUE;
    pd.DepthStencilState.DepthEnable = TRUE;
    pd.DepthStencilState.DepthWriteMask = D3D12_DEPTH_WRITE_MASK_ALL;
    pd.DepthStencilState.DepthFunc = D3D12_COMPARISON_FUNC_LESS;
    pd.DSVFormat = DXGI_FORMAT_D32_FLOAT;
    pd.PrimitiveTopologyType = D3D12_PRIMITIVE_TOPOLOGY_TYPE_TRIANGLE;
    pd.NumRenderTargets = 3;
    pd.RTVFormats[0] = DXGI_FORMAT_R8G8B8A8_UNORM;
    pd.RTVFormats[1] = DXGI_FORMAT_R8G8B8A8_UNORM;
    pd.RTVFormats[2] = DXGI_FORMAT_R32G32B32A32_UINT;
    pd.SampleDesc.Count = 1;
    if (FAILED(hr = ID3D12Device_CreateGraphicsPipelineState(dev, &pd, &IID_ID3D12PipelineState, (void **)&pso)))
        return fail("CreateGraphicsPipelineState (DXIL)", hr);

    D3D12_COMMAND_QUEUE_DESC qd = { D3D12_COMMAND_LIST_TYPE_DIRECT };
    ID3D12Device_CreateCommandQueue(dev, &qd, &IID_ID3D12CommandQueue, (void **)&queue);
    ID3D12Device_CreateCommandAllocator(dev, D3D12_COMMAND_LIST_TYPE_DIRECT, &IID_ID3D12CommandAllocator,
                                        (void **)&alloc);
    ID3D12Device_CreateCommandList(dev, 0, D3D12_COMMAND_LIST_TYPE_DIRECT, alloc, pso, &IID_ID3D12GraphicsCommandList,
                                   (void **)&list);

    static const DXGI_FORMAT fmts[3] = { DXGI_FORMAT_R8G8B8A8_UNORM, DXGI_FORMAT_R8G8B8A8_UNORM,
                                         DXGI_FORMAT_R32G32B32A32_UINT };
    ID3D12Resource *rt[3];
    D3D12_DESCRIPTOR_HEAP_DESC rhd = { D3D12_DESCRIPTOR_HEAP_TYPE_RTV, 3 };
    ID3D12Device_CreateDescriptorHeap(dev, &rhd, &IID_ID3D12DescriptorHeap, (void **)&rtv_heap);
    UINT rinc = ID3D12Device_GetDescriptorHandleIncrementSize(dev, D3D12_DESCRIPTOR_HEAP_TYPE_RTV);
    D3D12_CPU_DESCRIPTOR_HANDLE rtv[3];
    float zero[4] = { 0, 0, 0, 0 };
    for (int t = 0; t < 3; t++) {
        D3D12_CLEAR_VALUE cv = { fmts[t] };
        rt[t] = make_texture(dev, fmts[t], D3D12_RESOURCE_FLAG_ALLOW_RENDER_TARGET, D3D12_RESOURCE_STATE_RENDER_TARGET, &cv);
        rtv[t].ptr = ID3D12DescriptorHeap_GetCPUDescriptorHandleForHeapStart(rtv_heap).ptr + rinc * t;
        ID3D12Device_CreateRenderTargetView(dev, rt[t], NULL, rtv[t]);
        ID3D12GraphicsCommandList_ClearRenderTargetView(list, rtv[t], zero, 0, NULL);
    }
    D3D12_CLEAR_VALUE dcv = { DXGI_FORMAT_D32_FLOAT };
    dcv.DepthStencil.Depth = 1.0f;
    ID3D12Resource *ds = make_texture(dev, DXGI_FORMAT_D32_FLOAT, D3D12_RESOURCE_FLAG_ALLOW_DEPTH_STENCIL,
                                      D3D12_RESOURCE_STATE_DEPTH_WRITE, &dcv);
    D3D12_DESCRIPTOR_HEAP_DESC dhd = { D3D12_DESCRIPTOR_HEAP_TYPE_DSV, 1 };
    ID3D12Device_CreateDescriptorHeap(dev, &dhd, &IID_ID3D12DescriptorHeap, (void **)&dsv_heap);
    D3D12_CPU_DESCRIPTOR_HANDLE dsv = ID3D12DescriptorHeap_GetCPUDescriptorHandleForHeapStart(dsv_heap);
    ID3D12Device_CreateDepthStencilView(dev, ds, NULL, dsv);
    ID3D12GraphicsCommandList_ClearDepthStencilView(list, dsv, D3D12_CLEAR_FLAG_DEPTH, 1.0f, 0, 0, NULL);

    float v[4] = { 0.2f, 0.4f, 0.6f, 0.8f };
    ID3D12GraphicsCommandList_OMSetRenderTargets(list, 3, rtv, FALSE, &dsv);
    D3D12_VIEWPORT vpt = { 0, 0, W, H, 0, 1 };
    D3D12_RECT sc = { 0, 0, W, H };
    ID3D12GraphicsCommandList_RSSetViewports(list, 1, &vpt);
    ID3D12GraphicsCommandList_RSSetScissorRects(list, 1, &sc);
    ID3D12GraphicsCommandList_SetGraphicsRootSignature(list, rs);
    ID3D12GraphicsCommandList_SetGraphicsRoot32BitConstants(list, 0, 4, v, 0);
    ID3D12GraphicsCommandList_IASetPrimitiveTopology(list, D3D_PRIMITIVE_TOPOLOGY_TRIANGLELIST);
    ID3D12GraphicsCommandList_DrawInstanced(list, 3, 2, 0, 0);

    UINT64 slot = 256 * 4 * H; /* 16 bytes x 64 = 1024 per row is enough for every target */
    ID3D12Resource *rb = make_buffer(dev, D3D12_HEAP_TYPE_READBACK, slot * 4, D3D12_RESOURCE_STATE_COPY_DEST);
    for (int t = 0; t < 3; t++) {
        transition(list, rt[t], D3D12_RESOURCE_STATE_RENDER_TARGET, D3D12_RESOURCE_STATE_COPY_SOURCE);
        copy_out(list, rb, slot * t, rt[t], fmts[t], 1024);
    }
    transition(list, ds, D3D12_RESOURCE_STATE_DEPTH_WRITE, D3D12_RESOURCE_STATE_COPY_SOURCE);
    copy_out(list, rb, slot * 3, ds, DXGI_FORMAT_R32_TYPELESS, 256);
    if (FAILED(hr = ID3D12GraphicsCommandList_Close(list)))
        return fail("Close", hr);
    ID3D12CommandQueue_ExecuteCommandLists(queue, 1, (ID3D12CommandList **)&list);
    ID3D12Device_CreateFence(dev, 0, D3D12_FENCE_FLAG_NONE, &IID_ID3D12Fence, (void **)&fence);
    HANDLE ev = CreateEventA(NULL, FALSE, FALSE, NULL);
    ID3D12CommandQueue_Signal(queue, fence, 1);
    ID3D12Fence_SetEventOnCompletion(fence, 1, ev);
    if (WaitForSingleObject(ev, 10000) != WAIT_OBJECT_0)
        return fail("GPU timeout", E_FAIL);

    unsigned char *px = NULL;
    ID3D12Resource_Map(rb, 0, NULL, (void **)&px);
    int x = 32, y = 32, bad = 0;
    unsigned char *a = px + y * 1024 + x * 4;
    unsigned char *b = px + slot + y * 1024 + x * 4;
    UINT *c = (UINT *)(px + slot * 2 + y * 1024 + x * 16);
    float d;
    memcpy(&d, px + slot * 3 + y * 256 + x * 4, 4);
    printf("RT0 = %d %d %d %d (want 51 102 153 204)\n", a[0], a[1], a[2], a[3]);
    printf("RT1 = %d %d %d %d (want 65 65 0 255)\n", b[0], b[1], b[2], b[3]);
    printf("RT2 = %u %u %u %u (want 7, front face 1 or 2, 32, 32)\n", c[0], c[1], c[2], c[3]);
    printf("depth = %f (want 0.25)\n", d);
    int wa[4] = { 51, 102, 153, 204 }, wb[4] = { 65, 65, 0, 255 };
    for (int i = 0; i < 4; i++) {
        bad += abs(a[i] - wa[i]) > 1;
        bad += abs(b[i] - wb[i]) > 1;
    }
    bad += c[0] != 7 || (c[1] != 1 && c[1] != 2) || c[2] != 32 || c[3] != 32;
    bad += d < 0.249f || d > 0.251f;
    if (bad) {
        printf("FAIL\n");
        return 1;
    }
    printf("PASS\n");
    return 0;
}
